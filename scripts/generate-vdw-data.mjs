/* global fetch, AbortSignal */
// Extract only the approved vdW column; never regenerate masses/covalent radii/settings.
import { createHash } from 'node:crypto'
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { resolve } from 'node:path'
import { format } from 'prettier'

const root = fileURLToPath(new URL('../', import.meta.url))
const revision = '67e08702c5e9e8541d9944824b10edfb718d61e8'
const base = `https://raw.githubusercontent.com/lmmentel/mendeleev-data/${revision}/`
const sources = {
  'data/json/elements.json': '8ea60a0afe8ba3a0d23af9220968e3d08c988d3d6d773cf032fe6a34c125ee95',
  'data/json/propertymetadata.json':
    '31f9e11a9381ddc2ec30ea0e1d60e6b8a6f48a9a5bb8c9dbad021a0b5d79a588',
  LICENSE: 'bcbc87d5f4ce66074a3a51d84a44df0de94d0f1a4cc794e4c17bc497b226e5eb'
}
const digest = (bytes) => createHash('sha256').update(bytes).digest('hex')
const received = {}
await mkdir(resolve(root, '.tmp/vdw-data'), { recursive: true })
for (const [name, expected] of Object.entries(sources)) {
  const cache = resolve(root, '.tmp/vdw-data', name.replaceAll('/', '_'))
  let bytes
  try {
    bytes = await readFile(cache)
  } catch {
    const response = await fetch(base + name, { signal: AbortSignal.timeout(30000) })
    if (!response.ok) throw new Error(`${name}: HTTP ${response.status}`)
    bytes = Buffer.from(await response.arrayBuffer())
    await writeFile(cache, bytes)
  }
  if (digest(bytes) !== expected) throw new Error(`Source digest mismatch: ${name}`)
  received[name] = bytes.toString('utf8')
}
const records = JSON.parse(received['data/json/elements.json'])
const property = JSON.parse(received['data/json/propertymetadata.json']).find(
  (entry) => entry.attribute_name === 'vdw_radius_alvarez'
)
if (property.unit !== 'pm' || property.citation_keys !== 'Alvarez2013,Vogt2014')
  throw new Error('Unexpected radius semantics.')
const values = records.filter((entry) => entry.vdw_radius_alvarez !== null)
const missing = records
  .filter((entry) => entry.vdw_radius_alvarez === null)
  .map((entry) => entry.symbol)
if (records.length !== 118 || values.length !== 94 || missing.length !== 24)
  throw new Error('Unexpected radius coverage.')
const output = `// Generated by scripts/generate-vdw-data.mjs from pinned mendeleev-data 1.1.0.\n// Alvarez2013 with Vogt2014 noble-gas updates, pm / 100 -> Å; missing values stay absent.\nexport const vanDerWaalsRadii: Readonly<Record<string, number>> = {\n${values.map((entry) => `  ${entry.symbol}: ${entry.vdw_radius_alvarez / 100}`).join(',\n')}\n}\n`
const target = 'packages/alchemion/src/core/data/vdw-radii.ts'
await writeFile(resolve(root, target), output)
const manifest = {
  generatedBy: 'scripts/generate-vdw-data.mjs',
  dataset: 'mendeleev-data 1.1.0 Alvarez/Vogt',
  revision,
  field: 'vdw_radius_alvarez',
  transformation: 'pm / 100 -> angstrom; null remains missing; no covalent/mass/setting changes',
  license: 'MIT; Copyright (c) 2024 Lukasz Mentel',
  references: ['10.1039/C3DT50599E', '10.1021/ic501364h', '10.1021/ic502140y'],
  sources: Object.fromEntries(
    Object.entries(sources).map(([name, sha256]) => [name, { url: base + name, sha256 }])
  ),
  outputs: { [target]: digest(output) },
  counts: { elements: 118, present: 94, missing: 24 },
  missing,
  limitation:
    'A compiled radius convention including estimates, not 94 independently measured constants.'
}
await writeFile(
  resolve(root, 'packages/alchemion/VDW_DATA_MANIFEST.json'),
  await format(JSON.stringify(manifest), { parser: 'json' })
)
await writeFile(resolve(root, 'packages/alchemion/src/core/data/VDW_LICENSE.txt'), received.LICENSE)
console.log(`Extracted ${values.length} vdW radii; ${missing.length} explicitly missing.`)
