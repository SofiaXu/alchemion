def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def source_bytes(name: str, url: str, expected: str | None) -> bytes:
    path = CACHE / name
    if path.exists():
        data = path.read_bytes()
    else:
        data = urllib.request.urlopen(url, timeout=60).read()
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    if expected is not None and digest(data) != expected:
        raise ValueError(f"Upstream source changed: {name}")
    return data


def write_table(name: str, export: str, type_name: str, records: list) -> Path:
    # Each generated record remains reviewable on one line; Prettier preserves it.
    text = (
        "// Generated by scripts/scientific-data/generate.py. Do not edit by hand.\n"
        f"import type {{ {type_name} }} from './types'\n\n"
        "// prettier-ignore\n"
        f"export const {export}: readonly {type_name}[] = [\n"
        + ",\n".join("  " + json.dumps(row, ensure_ascii=False, separators=(",", ":")) for row in records)
        + "\n]\n"
    )
    path = OUTPUT / name
    path.write_text(text, encoding="utf-8", newline="\n")
    return path


def main() -> None:
    if sys.version_info[:2] != (3, 12):
        raise RuntimeError("The pinned reference interpreter is Python 3.12.")
    installed = {name: importlib.metadata.version(name) for name in PINNED}
    if installed != PINNED:
        raise RuntimeError(f"Unexpected reference environment: {installed}")
    import numpy as np
    import periodictable as pt
    import periodictable.mass as mass_module
    import spglib

    upstream = {}
    contents = {}
    for name, (url, expected) in SOURCES.items():
        data = source_bytes(name, url, expected)
        contents[name] = data
        upstream[name] = {"url": url, "sha256": digest(data)}
    # Verify installed scientific sources against the reviewed fixed-tag bytes.
    package_root = Path(pt.__file__).parent
    for filename in ("core.py", "mass.py", "covalent_radius.py"):
        installed_bytes = (package_root / filename).read_bytes().replace(b"\r\n", b"\n")
        raw_bytes = contents[f"periodictable/{filename}"].replace(b"\r\n", b"\n")
        if installed_bytes != raw_bytes:
            raise RuntimeError(f"Installed periodictable source differs: {filename}")
    standard_atomic_numbers = {int(line.split()[0]) for line in mass_module.element_mass.splitlines()}
    mass_provenance = {
        "source": SOURCES["periodictable/mass.py"][0],
        "version": "periodictable 2.0.2 / CIAAW 2021 / AME2020",
        "reference": "10.1515/pac-2019-0603; 10.1088/1674-1137/abddaf",
    }
    radius_provenance = {
        "source": SOURCES["periodictable/covalent_radius.py"][0],
        "version": "periodictable 2.0.2 / Cordero 2008",
        "reference": "10.1039/B801115J",
    }
    elements = []
    for number in range(1, 119):
        element = pt.elements[number]
        if number in standard_atomic_numbers:
            mass = {"value": element.mass, "kind": "standard-atomic-weight", "provenance": mass_provenance}
        else:
            isotope = int(round(element.mass))
            isotope_mass = element[isotope].mass
            if isotope_mass is None:
                raise RuntimeError(f"No representative isotope mass for {element}")
            mass = {"value": isotope_mass, "kind": "representative-isotope", "isotopeMassNumber": isotope, "provenance": mass_provenance}
        record = {"atomicNumber": number, "symbol": element.symbol, "name": element.name, "mass": mass}
        if element.covalent_radius is not None:
            record["covalentRadius"] = {"value": element.covalent_radius, "standardUncertainty": element.covalent_radius_uncertainty, "provenance": radius_provenance}
        elements.append(record)
    assert len(elements) == 118
    assert [e["atomicNumber"] for e in elements if "covalentRadius" in e] == list(range(1, 97))

    settings = []
    max_rational_error = 0.0
    for hall in range(1, 531):
        group = spglib.get_spacegroup_type(hall)
        operations = spglib.get_symmetry_from_database(hall)
        assert group is not None and operations is not None and group.hall_number == hall
        encoded = []
        for rotation, translation in zip(operations["rotations"], operations["translations"]):
            # The SDK stores columns. spglib Python exposes conventional matrix rows.
            vector = [int(n) for n in rotation.T.flatten()]
            assert abs(round(np.linalg.det(rotation))) == 1
            for value in translation:
                rational = Fraction(float(value)).limit_denominator(48)
                error = abs(float(rational) - value)
                max_rational_error = max(max_rational_error, error)
                assert error <= 1e-12
                vector.extend([rational.numerator, rational.denominator])
            encoded.append(vector)
        settings.append({"hallNumber": hall, "itNumber": group.number, "hermannMauguin": group.international_short, "hermannMauguinFull": group.international_full, "hallSymbol": group.hall_symbol, "choice": group.choice, "operations": encoded})
    assert len({s["itNumber"] for s in settings}) == 230
    OUTPUT.mkdir(parents=True, exist_ok=True)
    generated = [write_table("elements.ts", "elementData", "ElementRecord", elements), write_table("space-groups.ts", "spaceGroupData", "RawSpaceGroupSetting", settings)]
    manifest = {
        "generatedBy": "scripts/scientific-data/generate.py",
        "python": ".".join(map(str, sys.version_info[:3])),
        "tools": installed,
        "sources": upstream,
        "outputs": {str(path.relative_to(ROOT)).replace("\\", "/"): digest(path.read_bytes()) for path in generated},
        "counts": {"elements": len(elements), "covalentRadii": sum("covalentRadius" in e for e in elements), "hallSettings": len(settings), "internationalNumbers": 230, "operations": sum(len(s["operations"]) for s in settings)},
        "maximumTranslationRationalizationError": max_rational_error,
        "radiusConvention": "Angstrom; C sp3; Mn/Fe/Co low spin; absent for atomic numbers 97-118; uncertainty zero is retained as reported, not a guarantee of exactness.",
        "massConvention": "u; standard atomic weights for elements in periodictable.mass.element_mass (CIAAW2021); other elements use the explicitly identified representative isotope and its AME2020 mass, not a natural mean.",
        "rotationConvention": "column vectors; operation IDs are hall:<Hall number>:<zero-based upstream index>; exact reduced rational translations.",
    }
    manifest_path = OUTPUT / "manifest.json"
    manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")
    notices = """# Third-party scientific data notices

These notices apply to the verified M3 tables in `core/data`. Historical viewer/format assets remain separately inventoried in the project data-source ledger and are not the source of the M3 tables.

## periodictable 2.0.2

Author: Paul Kienzle. The upstream `core.py` and `mass.py` state “This program is public domain”; `covalent_radius.py` states “This program is in the public domain”. Fixed-tag sources, byte hashes and conversion records are in the generated `core/data/manifest.json` (also distributed as `SCIENTIFIC_DATA_MANIFEST.json`).

- Element identities: https://github.com/pkienzle/periodictable/blob/v2.0.2/periodictable/core.py
- Masses: https://github.com/pkienzle/periodictable/blob/v2.0.2/periodictable/mass.py ; CIAAW 2021 abridged standard atomic weights, Prohaska et al., DOI 10.1515/pac-2019-0603; AME2020 isotope masses, Wang et al., DOI 10.1088/1674-1137/abddaf.
- Covalent radii: https://github.com/pkienzle/periodictable/blob/v2.0.2/periodictable/covalent_radius.py ; Beatriz Cordero et al., Covalent radii revisited, Dalton Transactions (2008), 2832–2838, DOI 10.1039/B801115J.

The radius table uses C sp3 and Mn/Fe/Co low spin. Atomic numbers 97–118 have no radius and are not assigned a substitute. Reported zero uncertainties are retained and do not assert exact values. Mass records distinguish standard atomic weights from representative isotope masses; the latter carry the selected isotope mass number.

## spglib 2.6.0

Sources: https://github.com/spglib/spglib/tree/v2.6.0 ; Hall settings 1–530 from `get_spacegroup_type` and `get_symmetry_from_database`. Integer rotations are transposed to SDK column storage, translations are reduced to exact rational numbers after checking the round-trip error. Operation order is retained; no setting is guessed from an international number.

Original BSD 3-Clause license from https://github.com/spglib/spglib/blob/v2.6.0/COPYING:

```text
""" + contents["spglib/COPYING"].decode("utf-8").rstrip() + "\n```\n"
    (ROOT / "packages/alchemion/THIRD_PARTY_NOTICES.md").write_text(notices, encoding="utf-8", newline="\n")
    # A manifest copy is carried by the package files whitelist, independent of bundler imports.
    (ROOT / "packages/alchemion/SCIENTIFIC_DATA_MANIFEST.json").write_bytes(manifest_path.read_bytes())
    print(json.dumps({"manifest": str(manifest_path.relative_to(ROOT)), "counts": manifest["counts"], "outputs": manifest["outputs"], "translationError": max_rational_error}, indent=2))


if __name__ == "__main__":
    main()
